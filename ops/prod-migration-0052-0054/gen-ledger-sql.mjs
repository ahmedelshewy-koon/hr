// Regenerates expected-ledger.sql and files.sha256 from the committed migration files.
// Drizzle's migrator records sha256(file text) and the journal `when`; on its next run it applies every journal
// entry whose `when` is newer than MAX(created_at). Hashes come from git blobs (LF), exactly what a Linux
// checkout or the CI release tarball contains.
// Usage (repo root): node ops/prod-migration-0052-0054/gen-ledger-sql.mjs
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";

const dir = "ops/prod-migration-0052-0054";
const blob = path => execFileSync("git", ["show", `HEAD:${path}`], { maxBuffer: 1 << 26 });
const sha = buf => createHash("sha256").update(buf).digest("hex");
const journal = JSON.parse(blob("drizzle-postgres/meta/_journal.json").toString()).entries;
const byIdx = idx => journal.find(e => e.idx === idx);
if (journal.at(-1).tag !== "0054_deleted_employee_email") throw new Error(`Journal ends at ${journal.at(-1).tag}; review this release first`);
journal.forEach((e, i) => { if (e.idx !== i || !/^[0-9a-z_-]+$/.test(e.tag) || (i && e.when <= journal[i - 1].when)) throw new Error(`Unexpected journal entry ${e.tag}`); });

const tuples = journal.map(e => `(${e.idx},''${e.tag}'',''${sha(blob(`drizzle-postgres/${e.tag}.sql`))}'',${e.when}::bigint)`).join(",");
writeFileSync(`${dir}/expected-ledger.sql`, [
  "-- GENERATED by gen-ledger-sql.mjs from the committed migrations. Do not edit by hand.",
  "-- expected_ledger: every journal entry as (idx, tag, sha256, created_at). Use as: WITH e(idx,tag,hash,created_at) AS :expected_ledger",
  `\\set expected_ledger '(VALUES ${tuples})'`,
  `\\set base_when ${byIdx(32).when}`,
  `\\set head_when ${journal.at(-1).when}`,
  "",
].join("\n"));

const files = ["drizzle-postgres/meta/_journal.json", "ops/hr-schema-contract.json", ...journal.map(e => `drizzle-postgres/${e.tag}.sql`)];
writeFileSync(`${dir}/files.sha256`, files.map(f => `${sha(blob(f))}  ${f}`).join("\n") + "\n");
console.log(`journal=${journal.length} base=${byIdx(32).tag} head=${journal.at(-1).tag}; pinned ${files.length} files`);
