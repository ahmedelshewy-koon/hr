// Regenerates expected-ledger.sql, files.sha256 and known-migration-versions.json from git.
// Drizzle's migrator records sha256(file text) and the journal `when`; on its next run it applies every journal
// entry whose `when` is newer than MAX(created_at). Current hashes come from HEAD's git blobs (LF), exactly what a
// Linux checkout or the CI release tarball contains. The known-versions catalog lists every committed version of
// every migration file on every ref (LF and CRLF variants, since a Windows checkout hashes CRLF text), so the
// lineage check can tell "edited after it was applied" apart from "not from this repository at all".
// Usage (repo root): node ops/prod-migration-0052-0054/gen-ledger-sql.mjs
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";

const dir = "ops/prod-migration-0052-0054";
const git = (...args) => execFileSync("git", args, { maxBuffer: 1 << 28, stdio: ["ignore", "pipe", "ignore"] });
const blobAt = (rev, path) => { try { return git("show", `${rev}:${path}`); } catch { return null; } };
const sha = buf => createHash("sha256").update(buf).digest("hex");
const journal = JSON.parse(blobAt("HEAD", "drizzle-postgres/meta/_journal.json").toString()).entries;
const packageTags = ["0052_timesheet_management", "0053_payroll_rebuild", "0054_deleted_employee_email"];
if (journal.at(-1).tag !== "0054_deleted_employee_email") throw new Error(`Journal ends at ${journal.at(-1).tag}; review this release first`);
journal.forEach((e, i) => { if (e.idx !== i || !/^[0-9a-z_-]+$/.test(e.tag) || (i && e.when <= journal[i - 1].when)) throw new Error(`Unexpected journal entry ${e.tag}`); });

const tuples = journal.map(e => `(${e.idx},''${e.tag}'',''${sha(blobAt("HEAD", `drizzle-postgres/${e.tag}.sql`))}'',${e.when}::bigint)`).join(",");
const whenOf = tag => journal.find(e => e.tag === tag).when;
writeFileSync(`${dir}/expected-ledger.sql`, [
  "-- GENERATED by gen-ledger-sql.mjs from the committed migrations. Do not edit by hand.",
  "-- expected_ledger: every journal entry as (idx, tag, sha256, created_at). Use as: WITH e(idx,tag,hash,created_at) AS :expected_ledger",
  `\\set expected_ledger '(VALUES ${tuples})'`,
  `\\set package_whens '${packageTags.map(whenOf).join(",")}'`,
  `\\set head_when ${journal.at(-1).when}`,
  "",
].join("\n"));

const files = ["drizzle-postgres/meta/_journal.json", "ops/hr-schema-contract.json", "ops/hr-schema-audit.sh", ...journal.map(e => `drizzle-postgres/${e.tag}.sql`)];
writeFileSync(`${dir}/files.sha256`, files.map(f => `${sha(blobAt("HEAD", f))}  ${f}`).join("\n") + "\n");

// Every committed (tag, when, text) on every ref, oldest commit first.
const commits = git("rev-list", "--all", "--reverse", "--", "drizzle-postgres").toString().split("\n").filter(Boolean);
const versions = new Map();
for (const commit of commits) {
  const journalBlob = blobAt(commit, "drizzle-postgres/meta/_journal.json");
  if (!journalBlob) continue;
  let entries; try { entries = JSON.parse(journalBlob.toString()).entries; } catch { continue; }
  for (const e of entries) {
    const text = blobAt(commit, `drizzle-postgres/${e.tag}.sql`);
    if (!text) continue;
    const lf = text.toString().replace(/\r\n/g, "\n");
    for (const [eol, body] of [["lf", lf], ["crlf", lf.replace(/\n/g, "\r\n")]]) {
      const hash = sha(body);
      const key = `${e.tag}|${e.when}|${hash}`;
      if (!versions.has(key)) versions.set(key, { tag: e.tag, when: e.when, hash, eol, commit: commit.slice(0, 12) });
    }
  }
}
writeFileSync(`${dir}/known-migration-versions.json`, JSON.stringify({
  generated_by: "gen-ledger-sql.mjs", note: "every committed version of every migration, LF and CRLF hashes; first commit seen",
  commits_scanned: commits.length, versions: [...versions.values()],
}, null, 1) + "\n");
console.log(`journal=${journal.length} head=${journal.at(-1).tag}; pinned ${files.length} files; ${versions.size} known versions from ${commits.length} commits`);
