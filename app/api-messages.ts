const GENERIC_LOAD = "تعذر تحميل البيانات. حاول مرة أخرى.";
const GENERIC_ACTION = "تعذر تنفيذ الإجراء. حاول مرة أخرى، وإذا استمرت المشكلة فتواصل مع مدير النظام.";

const isArabicInterface = () => typeof document !== "undefined" && document.documentElement.lang === "ar";
const hasArabic = (value: string) => /[؀-ۿ]/.test(value);

/**
 * Returns `message` unchanged for the English interface (or when it is already Arabic).
 * For the Arabic interface it returns the approved Arabic wording, or a generic Arabic
 * sentence when the English message is not one we know.
 */
export function localizeApiMessage(message: unknown, rtl: boolean = isArabicInterface()): string {
  const text = String(message ?? "").trim();
  if (!rtl || !text || hasArabic(text)) return text;
  const exact = EXACT[text];
  if (exact) return exact;
  const required = /^(.+) is required$/.exec(text);
  if (required) return FIELD_NAMES[required[1]] ? `حقل «${FIELD_NAMES[required[1]]}» مطلوب` : "بيانات مطلوبة غير مكتملة";
  const fileSize = /^File exceeds the (\d+) MB limit$/.exec(text);
  if (fileSize) return `حجم الملف أكبر من الحد المسموح (${fileSize[1]} ميجابايت)`;
  const status = /^Request failed \((\d{3})\)$/.exec(text);
  if (status) return `تعذر تنفيذ الطلب (${status[1]})`;
  if (/^Invalid .+: .+ → .+$/.test(text)) return "هذا الانتقال غير مسموح به من الحالة الحالية";
  if (/^Duplicate .+ is not allowed$/.test(text)) return "تم تسجيل هذا الحدث من قبل";
  if (/^Unable to (load|retrieve|verify|check|generate|reload|open)/i.test(text)) return GENERIC_LOAD;
  return GENERIC_ACTION;
}
